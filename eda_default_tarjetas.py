filas = []
for nombre, m in modelos.items():
    for conjunto, Xs, ys in [('train', X_train, y_train), ('test', X_test, y_test)]:
        pred = m.predict(Xs)
        filas.append({'Modelo': nombre, 'Conjunto': conjunto,
                      'Accuracy': accuracy_score(ys, pred),
                      'Precision': precision_score(ys, pred),
                      'Recall': recall_score(ys, pred),
                      'F1': f1_score(ys, pred)})

metricas = pd.DataFrame(filas).round(3)
metricas

fig, axes = plt.subplots(1, 2, figsize=(12, 5))
