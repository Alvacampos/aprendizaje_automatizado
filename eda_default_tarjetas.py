# Parte 2 – Modelado

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

datos = df.copy()   # copia: el df original queda intacto para la Parte 1

# Duplicados: se quitan para que no queden copias en train y test a la vez
datos = datos.drop_duplicates()

# Códigos no documentados → "otros"
datos['EDUCATION'] = datos['EDUCATION'].replace({0: 4, 5: 4, 6: 4})
datos['MARRIAGE'] = datos['MARRIAGE'].replace({0: 3})

print(datos.shape)
print(datos['EDUCATION'].value_counts().sort_index().to_dict())
print(datos['MARRIAGE'].value_counts().sort_index().to_dict())

# Selección: SEX por criterio ético; BILL_AMT2-6 por redundancia con BILL_AMT1
datos = datos.drop(columns=['SEX', 'BILL_AMT2', 'BILL_AMT3', 'BILL_AMT4', 'BILL_AMT5', 'BILL_AMT6'])

# One-hot encoding de las categóricas sin orden
datos = pd.get_dummies(datos, columns=['EDUCATION', 'MARRIAGE'], drop_first=True, dtype=int)

print(datos.shape)
datos.columns.tolist()

X = datos.drop(columns='DEFAULT')   # variables de entrada
y = datos['DEFAULT']                # lo que queremos predecir

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=42)

# Escalado: el scaler se ajusta SOLO con train
scaler = StandardScaler()
X_train_esc = scaler.fit_transform(X_train)
X_test_esc = scaler.transform(X_test)

print("Train:", X_train.shape, "| Test:", X_test.shape)
print("% default train:", round(y_train.mean(), 3), "| test:", round(y_test.mean(), 3))

"""### Preparación de datos

Limpieza: saqué las 35 filas duplicadas. En el EDA las había dejado, pero para modelar es mejor
quitarlas: si una copia queda en train y otra en test, el modelo estaría evaluándose con datos
que ya vio. También agrupé los códigos no documentados: EDUCATION 0, 5 y 6 pasan a 4 ("otros")
y MARRIAGE 0 pasa a 3 ("otros").

Selección de variables: dejé afuera SEX porque usar el sexo para decidir sobre un crédito puede
ser discriminatorio y además aportaba poco. De las facturas me quedé solo con BILL_AMT1, porque
estaban muy correlacionadas entre sí y repetían información.

Codificación: EDUCATION y MARRIAGE pasaron a one-hot encoding (columnas de 0 y 1), porque son
categorías sin un orden numérico real. Las variables PAY_X las dejé como números porque ahí el
orden sí tiene sentido: más meses de atraso es peor.

No apliqué logaritmo a los montos porque BILL_AMT1 tiene valores negativos y el logaritmo no
los admite. Con el escalado alcanza.

División y escalado: separé 80% para entrenar y 20% para evaluar, manteniendo el 22% de default
en las dos partes. Escalé las variables con StandardScaler solo para la Regresión Logística
(Random Forest no lo necesita). El escalador se ajusta solo con los datos de train, para que no
se filtre información del conjunto de test.
"""

from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import StratifiedKFold, cross_val_score, GridSearchCV
from sklearn.pipeline import make_pipeline

# Validación cruzada: 5 particiones, manteniendo el 22% de default en cada una
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

# Pipeline: escala y después entrena, como una sola unidad
lr = make_pipeline(StandardScaler(),
                   LogisticRegression(class_weight='balanced', max_iter=1000))

f1_lr = cross_val_score(lr, X_train, y_train, cv=cv, scoring='f1')
print("Regresión Logística - F1 por fold:", f1_lr.round(3), "| promedio:", f1_lr.mean().round(3))

lr.fit(X_train, y_train)   # entrenamiento final con todo el train

param_grid = {'max_depth': [5, 10, 15, None]}

grid_rf = GridSearchCV(
    RandomForestClassifier(n_estimators=100, class_weight='balanced', random_state=42, n_jobs=-1),
    param_grid, cv=cv, scoring='f1', return_train_score=True)
grid_rf.fit(X_train, y_train)

res = pd.DataFrame(grid_rf.cv_results_)[['param_max_depth', 'mean_train_score', 'mean_test_score']]
res.columns = ['max_depth', 'F1 train', 'F1 validación']
print(res.round(3))
print("\nMejor max_depth:", grid_rf.best_params_['max_depth'])

rf = grid_rf.best_estimator_   # se queda con el mejor modelo

from sklearn.linear_model import LogisticRegression
